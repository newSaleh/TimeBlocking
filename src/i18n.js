export const STRINGS = { ar: AR, en: EN };

export function translator(lang) {
  const dict = STRINGS[lang] || AR;
  const rules = new Intl.PluralRules(lang === 'ar' ? 'ar' : 'en');
  return function t(key, vars) {
    let s = dict[key];
    if (s == null) s = EN[key] != null ? EN[key] : key;
    if (typeof s === 'object') {
      const n = vars && vars.n;
      s = s[rules.select(n)] || s.other;
    }
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ''));
    return s;
  };
}
